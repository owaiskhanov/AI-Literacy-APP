// Converts the word "Literacy" (Sacramento monoline script font) into SVG path data
// so it can be animated with a handwriting "draw-on" effect.
// Run: node scripts/generate-literacy-path.js
const fs = require('fs');
const path = require('path');
const opentype = require('opentype.js');

const FONT = path.join(
  __dirname,
  '../node_modules/@expo-google-fonts/sacramento/400Regular/Sacramento_400Regular.ttf'
);
const WORD = 'Literacy';
const SIZE = 100;

const buf = fs.readFileSync(FONT);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const glyphs = [...WORD].map((c) => font.charToGlyph(c));
const scale = SIZE / font.unitsPerEm;

const n = (v) => +v.toFixed(2);
function toD(cmds) {
  return cmds
    .map((c) => {
      switch (c.type) {
        case 'M': return `M${n(c.x)} ${n(c.y)}`;
        case 'L': return `L${n(c.x)} ${n(c.y)}`;
        case 'Q': return `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
        case 'C': return `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
        default: return 'Z';
      }
    })
    .join('');
}

function pathLength(cmds) {
  let len = 0, cx = 0, cy = 0, sx = 0, sy = 0;
  const N = 16;
  for (const c of cmds) {
    if (c.type === 'M') { cx = sx = c.x; cy = sy = c.y; continue; }
    if (c.type === 'Z') { len += Math.hypot(sx - cx, sy - cy); cx = sx; cy = sy; continue; }
    let px = cx, py = cy;
    for (let i = 1; i <= N; i++) {
      const t = i / N, u = 1 - t;
      let nx, ny;
      if (c.type === 'L') { nx = cx + (c.x - cx) * t; ny = cy + (c.y - cy) * t; }
      else if (c.type === 'Q') { nx = u*u*cx + 2*u*t*c.x1 + t*t*c.x; ny = u*u*cy + 2*u*t*c.y1 + t*t*c.y; }
      else { nx = u*u*u*cx + 3*u*u*t*c.x1 + 3*u*t*t*c.x2 + t*t*t*c.x; ny = u*u*u*cy + 3*u*u*t*c.y1 + 3*u*t*t*c.y2 + t*t*t*c.y; }
      len += Math.hypot(nx - px, ny - py); px = nx; py = ny;
    }
    cx = c.x; cy = c.y;
  }
  return len;
}

let x = 0;
const letters = [];
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;

glyphs.forEach((g, i) => {
  const p = g.getPath(x, SIZE, SIZE);
  const bb = p.getBoundingBox();
  if (isFinite(bb.x1)) {
    minX = Math.min(minX, bb.x1); minY = Math.min(minY, bb.y1);
    maxX = Math.max(maxX, bb.x2); maxY = Math.max(maxY, bb.y2);
  }
  letters.push({ d: toD(p.commands), length: +pathLength(p.commands).toFixed(1) });
  x += g.advanceWidth * scale;
  if (i < glyphs.length - 1) x += font.getKerningValue(g, glyphs[i + 1]) * scale;
});

const pad = 4;
const out = {
  viewBox: [minX - pad, minY - pad, maxX - minX + pad * 2, maxY - minY + pad * 2].map((n) => +n.toFixed(2)),
  letters,
};

fs.writeFileSync(
  path.join(__dirname, '../components/literacyPath.js'),
  '// Auto-generated by scripts/generate-literacy-path.js — do not edit.\nexport default ' +
    JSON.stringify(out, null, 2) +
    ';\n'
);
console.log('viewBox', out.viewBox, 'letters', letters.length);
