// Converts words into SVG path data using the Sacramento monoline script font,
// so they can be animated with an Apple "hello"-style handwriting effect.
// Run: node scripts/generate-script-paths.js
const fs = require('fs');
const path = require('path');
const opentype = require('opentype.js');

const FONT = path.join(
  __dirname,
  '../node_modules/@expo-google-fonts/sacramento/400Regular/Sacramento_400Regular.ttf'
);
const WORDS = ['Literacy', 'Back'];
const SIZE = 100;

const buf = fs.readFileSync(FONT);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const scale = SIZE / font.unitsPerEm;

// opentype.js's toPathData can emit NaN, so serialize commands ourselves and explicitly close contours
const n = (v) => +v.toFixed(2);
function toD(cmds) {
  let res = '';
  let inContour = false;
  for (const c of cmds) {
    if (c.type === 'M') {
      if (inContour) res += 'Z';
      res += `M${n(c.x)} ${n(c.y)}`;
      inContour = true;
    } else if (c.type === 'L') {
      res += `L${n(c.x)} ${n(c.y)}`;
    } else if (c.type === 'Q') {
      res += `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
    } else if (c.type === 'C') {
      res += `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
    } else if (c.type === 'Z') {
      res += 'Z';
      inContour = false;
    }
  }
  if (inContour) res += 'Z';
  return res;
}

// Approximate outline length by sampling each segment and including contour closure.
function pathLength(cmds) {
  let len = 0, cx = 0, cy = 0, sx = 0, sy = 0;
  let inContour = false;
  const N = 16;
  for (const c of cmds) {
    if (c.type === 'M') {
      if (inContour) {
        len += Math.hypot(sx - cx, sy - cy);
      }
      cx = sx = c.x;
      cy = sy = c.y;
      inContour = true;
      continue;
    }
    if (c.type === 'Z') {
      len += Math.hypot(sx - cx, sy - cy);
      cx = sx;
      cy = sy;
      inContour = false;
      continue;
    }
    let px = cx, py = cy;
    for (let i = 1; i <= N; i++) {
      const t = i / N, u = 1 - t;
      let nx, ny;
      if (c.type === 'L') {
        nx = cx + (c.x - cx) * t;
        ny = cy + (c.y - cy) * t;
      } else if (c.type === 'Q') {
        nx = u*u*cx + 2*u*t*c.x1 + t*t*c.x;
        ny = u*u*cy + 2*u*t*c.y1 + t*t*c.y;
      } else {
        nx = u*u*u*cx + 3*u*u*t*c.x1 + 3*u*t*t*c.x2 + t*t*t*c.x;
        ny = u*u*u*cy + 3*u*u*t*c.y1 + 3*u*t*t*c.y2 + t*t*t*c.y;
      }
      len += Math.hypot(nx - px, ny - py);
      px = nx;
      py = ny;
    }
    cx = c.x;
    cy = c.y;
  }
  if (inContour) {
    len += Math.hypot(sx - cx, sy - cy);
  }
  return len;
}

function wordToPaths(word) {
  // Map chars directly (skips GSUB shaping, which opentype.js can't handle for this font).
  const glyphs = [...word].map((c) => font.charToGlyph(c));
  let x = 0;
  const letters = [];
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  glyphs.forEach((g, i) => {
    const p = g.getPath(x, SIZE, SIZE);
    const bb = p.getBoundingBox();
    if (isFinite(bb.x1)) {
      minX = Math.min(minX, bb.x1); minY = Math.min(minY, bb.y1);
      maxX = Math.max(maxX, bb.x2); maxY = Math.max(maxY, bb.y2);
    }
    letters.push({ d: toD(p.commands), length: +pathLength(p.commands).toFixed(1) });
    x += g.advanceWidth * scale;
    if (i < glyphs.length - 1) x += font.getKerningValue(g, glyphs[i + 1]) * scale;
  });
  const pad = 4;
  return {
    viewBox: [minX - pad, minY - pad, maxX - minX + pad * 2, maxY - minY + pad * 2].map((v) => +v.toFixed(2)),
    letters,
  };
}

const out = Object.fromEntries(WORDS.map((w) => [w, wordToPaths(w)]));

fs.writeFileSync(
  path.join(__dirname, '../components/scriptPaths.js'),
  '// Auto-generated by scripts/generate-script-paths.js — do not edit.\nexport default ' +
    JSON.stringify(out, null, 2) +
    ';\n'
);
WORDS.forEach((w) => console.log(w, 'viewBox', out[w].viewBox));
